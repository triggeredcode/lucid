import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

/**
 * Writes THIRD_PARTY_NOTICES.md from the production dependencies pnpm installed: `node scripts/notices.mjs`.
 * `--check` fails when the file is out of date (run it after changing dependencies).
 */
const OUT = fileURLToPath(new URL("../THIRD_PARTY_NOTICES.md", import.meta.url));

// A license pnpm cannot read from a package, checked by hand against the package's own repository.
const KNOWN = { khroma: "MIT" };

const raw = execFileSync("pnpm", ["licenses", "list", "--prod", "--json"], {
  encoding: "utf8",
  maxBuffer: 50_000_000,
});
const byLicense = JSON.parse(raw);

const rows = [];
for (const [license, packages] of Object.entries(byLicense)) {
  for (const p of packages) {
    const name = p.name;
    const lic = license === "Unknown" && KNOWN[name] ? KNOWN[name] : license;
    for (const v of p.versions ?? [""]) rows.push({ lic, name, v, home: p.homepage ?? "" });
  }
}
rows.sort((a, b) => a.lic.localeCompare(b.lic) || a.name.localeCompare(b.name));

const groups = new Map();
for (const r of rows) groups.set(r.lic, [...(groups.get(r.lic) ?? []), r]);

const lines = [
  "# Third-party notices",
  "",
  "Lucid is built on open-source software. The packages below are bundled into the app (production dependencies of the desktop",
  "app and the MCP server). Each is under the license shown; the full license texts are in each package's folder in",
  "`node_modules`. Generated by `node scripts/notices.mjs`; do not edit by hand.",
  "",
  "## Notes",
  "",
  "- **MPL-2.0** (BlockNote: `@blocknote/core`, `@blocknote/mantine`, `@blocknote/react`): used unmodified as libraries. Its",
  "  source is at https://github.com/TypeCellOS/BlockNote. Lucid does not use BlockNote's `xl-*` packages (GPL or commercial).",
  "- **EPL-2.0** (`elkjs`, the graph layout engine behind Mermaid's ELK layout): used unmodified; source at https://github.com/kieler/elkjs.",
  "- **Tectonic** (MIT, https://tectonic-typesetting.github.io), the PDF engine, comes with the app as a separate program",
  "  (`Contents/Resources/bin/tectonic`), unmodified. The TeX support files it downloads the first time it makes a PDF come from",
  "  Tectonic's own bundle (the TeX Live distribution, under its various free licenses).",
  "- **Electron and Chromium** (MIT and BSD-style licenses, https://www.electronjs.org): the app's runtime. Their license texts are",
  "  in the app (`Contents/Resources/LICENSE` and `Contents/Resources/LICENSES.chromium.html`).",
  "- **LM Studio** is a separate application, not part of Lucid, that serves the language model.",
  "- Lucid's own code never copies from GPL projects (VoiceInk, whisper-writer).",
  "",
  `## Packages (${String(rows.length)})`,
];
for (const [lic, list] of groups) {
  lines.push("", `### ${lic} (${String(list.length)})`, "");
  for (const r of list) lines.push(`- ${r.name} ${r.v}${r.home ? ` — ${r.home}` : ""}`);
}
const text = `${lines.join("\n")}\n`;

if (process.argv.includes("--check")) {
  const current = (() => {
    try {
      return readFileSync(OUT, "utf8");
    } catch {
      return "";
    }
  })();
  if (current !== text) {
    console.error("THIRD_PARTY_NOTICES.md is out of date. Run: node scripts/notices.mjs");
    process.exit(1);
  }
  console.log("THIRD_PARTY_NOTICES.md is up to date.");
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT} (${String(rows.length)} packages)`);
}
